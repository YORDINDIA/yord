-- 013_contact_and_newsletter_tables.sql — create the two form-capture tables.
-- Apply after 012. Idempotent (`if not exists` throughout).
--
-- Why: `POST /api/contact` and `POST /api/newsletter` have always inserted into
-- `contact_submissions` and `newsletter_subscribers`, and `@yord/db-types`
-- declares both — but no migration, no `scripts/schema.sql`, and no doc ever
-- created them. Verified against the live project on 2026-10-05:
-- `information_schema.tables` returns nothing for either name, so both inserts
-- fail with a 400 from PostgREST.
--
-- Both routes handle that correctly (they log and return 500), so the failure is
-- loud rather than silent — a visitor sees "Failed to submit message. Please try
-- again." and "Failed to subscribe. Please try again." — but it means **no
-- contact message and no newsletter signup has ever been stored**. The footer
-- newsletter, the home newsletter section, and the contact page are all affected.
--
-- Columns mirror the two insert sites exactly (name/email/subject/message/
-- created_at/status, and email/subscribed_at) plus the `id` that `db-types`
-- declares. Unlike the migrated Shopify tables, `id` gets a real identity
-- default: those tables shipped `BIGINT PRIMARY KEY` with no default, which
-- makes a fresh migration fail on the first insert.
--
-- RLS is enabled with no policies on purpose, matching `analytics_events` (010):
-- both routes write through the secret key, which bypasses RLS, and nothing
-- reads these tables with the publishable key. An admin inbox added later should
-- read through the admin data layer's service client rather than a policy.

create table if not exists public.contact_submissions (
  id          bigint generated by default as identity primary key,
  name        text not null,
  email       text not null,
  subject     text not null,
  message     text not null,
  status      text default 'new',
  created_at  timestamptz not null default now()
);

-- `email` is unique so the route's "already subscribed?" probe cannot race a
-- concurrent insert into two rows, and so a duplicate signup fails on the
-- constraint instead of silently double-adding. The probe uses `.single()`,
-- which PostgREST reports as PGRST116 for both zero and many rows — uniqueness
-- is what keeps "many" impossible.
create table if not exists public.newsletter_subscribers (
  id            bigint generated by default as identity primary key,
  email         text not null unique,
  subscribed_at timestamptz not null default now()
);

create index if not exists newsletter_subscribers_email_idx
  on public.newsletter_subscribers (lower(email));

alter table public.contact_submissions     enable row level security;
alter table public.newsletter_subscribers  enable row level security;
